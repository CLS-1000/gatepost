#!/usr/bin/env python3
"""Build bin/verify.py: the gp-canon/1 verifier as ONE stdlib-only file a recipient can run.

usage: python3 tools/bundle_verify.py        (writes bin/verify.py)

Inlines gpcanon/canon.py, ed25519_verify.py, schema.py and verify.py in dependency
order. Tests run the bundle against the same tamper suite as the package.
"""
import ast
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["canon.py", "ed25519_verify.py", "schema.py", "verify.py"]


def build() -> str:
    # The CLI's --help prints __doc__. A module docstring must be the file's first
    # statement, ahead of `from __future__`, so lift gpcanon/verify.py's to the top.
    # Without this, every inlined docstring sits after the import and __doc__ is None.
    verify_src = (ROOT / "gpcanon" / "verify.py").read_text()
    doc = ast.get_docstring(ast.parse(verify_src), clean=False)
    parts = ["#!/usr/bin/env python3",
             "# Generated by tools/bundle_verify.py from gpcanon/ — edit the package, not this file.",
             '"""' + doc + '"""',
             "from __future__ import annotations", ""]
    for name in ORDER:
        src = (ROOT / "gpcanon" / name).read_text()
        src = src.replace("from __future__ import annotations\n", "")
        src = re.sub(r"^from \.[a-z_0-9]+ import [^\n]+\n", "", src, flags=re.M)
        if name == "verify.py":
            src = src.replace('if __name__ == "__main__":\n    sys.exit(main())\n', "")
        parts += [f"# ---- gpcanon/{name} " + "-" * (60 - len(name)), src]
        if name == "ed25519_verify.py":
            parts.append("ed25519_verify = verify\n")
    parts += ['if __name__ == "__main__":', "    sys.exit(main())", ""]
    return "\n".join(parts)


if __name__ == "__main__":
    out = ROOT / "bin" / "verify.py"
    out.parent.mkdir(exist_ok=True)
    text = build()
    out.write_text(text)
    out.chmod(0o755)
    print(f"wrote {out} ({len(text.splitlines())} lines, sha256 {hashlib.sha256(text.encode()).hexdigest()[:16]})")
